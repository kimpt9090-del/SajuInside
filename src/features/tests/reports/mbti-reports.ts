function buildSections(m: MbtiMeta): ReportSection[] {
  return [
    {
      id: "overview",
      title: "유형 종합 해석",
      subtitle: `${m.code} — ${m.nickname}`,
      highlight: m.overview[0],
      paragraphs: m.overview,
      tags: ["#MBTI", `#${m.code}`],
    },
    {
      id: "strength",
      title: "강점·재능",
      bullets: m.strengths,
      tags: ["#강점"],
    },
    {
      id: "weakness",
      title: "약점·스트레스 패턴",
      bullets: m.weaknesses,
      tags: ["#약점"],
    },
    {
      id: "career",
      title: "직업·커리어·학업",
      paragraphs: [m.career.intro],
      bullets: m.career.fields.map((f) => `추천 분야: ${f}`),
      tags: ["#커리어"],
    },
    {
      id: "love",
      title: "연애·대인관계",
      bullets: m.love,
      tags: ["#연애"],
    },
    ...((): ReportSection[] => {
      const marriage = getMbtiMarriageSection(m.code);
      return marriage ? [marriage] : [];
    })(),
    {
      id: "growth",
      title: "성장·발전 가이드",
      highlight: "유형은 '틀'이지 '운명'이 아닙니다. 강점을 키우고 약점을 의식하면 어떤 환경에서도 성장할 수 있습니다.",
      bullets: m.growth,
      tags: ["#성장"],
    },
    ...(m.famous
      ? [
          {
            id: "famous",
            title: "유사 유형·참고",
            paragraphs: [
              `${m.famous}. (유명인 MBTI는 추정·오락 목적이며, 개인과 100% 일치하지 않습니다.)`,
              "같은 유형이라도 성장 환경·경험에 따라 표현은 달라집니다. 자신만의 강점에 집중하세요.",
            ],
            tags: ["#참고"],
          } satisfies ReportSection,
        ]
      : []),
  ];
}

export function getMbtiReportSections(code: string): ReportSection[] {
  const m = TYPES[code];
  if (!m) return [];
  const quick = getQuickSummarySection("mbti", code);
  const base = quick ? [quick, ...buildSections(m)] : buildSections(m);
  return appendMbtiExtras(code, base);
}

export function getMbtiExtendedSummary(code: string): string {
  const m = TYPES[code];
  return m?.overview[0] ?? "";
}
