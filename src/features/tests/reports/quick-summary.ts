export function getQuickSummary(
  testId: string,
  resultId: string,
): QuickSummary | undefined {
  if (testId === "mbti" || testId === "mbti-full" || testId === "mbti-official") {
    return MBTI_QUICK[resultId.toUpperCase()];
  }
  return QUICK_SUMMARIES[testId]?.[resultId];
}

export function getQuickSummarySection(
  testId: string,
  resultId: string,
): ReportSection | null {
  const q = getQuickSummary(testId, resultId);
  if (!q) return null;
  return {
    id: "quick-summary",
    title: "30초 요약",
    subtitle: "바쁜 분을 위한 핵심 정리",
    highlight: q.oneLiner,
    bullets: q.bullets,
    paragraphs: [`오늘의 실천: ${q.actionTip}`],
    tags: ["#요약"],
  };
}
